test("a council member's addon follows the loot master's session and sends its vote", function()
    local ns = start()
    wow.raid({ SEREN, DORAN, ILSA, VESPERA })
    wow.message("Seren Vale", "RAID", "S", 301, 18000, "council", 30, "Seren Vale", "Seren Vale,Kadmai Moonwhisper", SASH)
    local s = ns.CouncilSession()
    eq(s.sid, 301)
    eq(s.mine, nil)
    eq(s.link, SASH)
    eq(s.phase, "bids")
    wow.message("Ilsa Marrow", "WHISPER", "B", 301, "ms", "BIS", "", "2.0", "")
    eq(s.bids["ilsa marrow"].resp, "ms")
    wow.message("Seren Vale", "WHISPER", "P", 301, "vote", 300)
    eq(s.phase, "vote")
    ns.SetVoteReason("upgrade", true)
    ns.Vote("ilsa marrow")
    local v = wow.messages("V")
    eq(#v, 1, "to Seren (the player is the other council member)")
    eq(v[1].target, "Seren Vale")
    eq(v[1][3], "ilsa marrow")
    eq(v[1][4], "upgrade")
    eq(s.votes["kadmai moonwhisper"], "ilsa marrow")
    wow.message("Seren Vale", "RAID", "E", 301, "Ilsa Marrow")
    eq(s.phase, "done")
    eq(s.winner, "Ilsa Marrow")
end)

