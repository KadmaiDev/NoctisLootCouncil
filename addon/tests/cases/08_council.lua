-- The council, on the loot master's addon and on a council member's.

local SASH = wow.link(18000, "Sash of the Unseen", 4)
local SEREN = { "Seren", "Vale", rank = "Officer", class = "PRIEST" }
local DORAN = { "Doran", "Pike", rank = "Officer", class = "WARRIOR" }
local ILSA = { "Ilsa", "Marrow", rank = "Raider", class = "WARLOCK" }
local VESPERA = { "Vespera", "Ashward", rank = "Raider", class = "WARLOCK" }
local ODO = { "Odo", "Fenwick", rank = "Trial", class = "MAGE" }
local BRAN = { "Bran", "Holloway", rank = "Social", class = "MAGE" }

-- The player is the loot master; Seren, Doran and the player are the council.
local function lootMaster()
    local ns = start()
    wow.raid({ SEREN, DORAN, ILSA, VESPERA, ODO, BRAN })
    wow.type("/nlc councillors Seren Vale, Doran Pike, Kadmai Moonwhisper")
    wow.type("/nlc council " .. SASH .. " Warlock priority")
    clearPrinted()
    return ns
end

local function bid(who, resp, tags, note, gain, gear)
    local s = wow.ns.CouncilSession()
    wow.message(who, "WHISPER", "B", s.sid, resp, tags or "", note or "", gain or "", gear or "")
end

local function vote(who, cand)
    wow.message(who, "WHISPER", "V", wow.ns.CouncilSession().sid, cand)
end

local function lastSaid() return wow.sent[#wow.sent] and wow.sent[#wow.sent][1] end

test("/nlc start on a council item opens bids: announced, and the pop-up's message lists the council", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    eq(wow.sent[1][1], "Council item: " .. SASH .. ". Use the pop-up, or /roll for main spec, /roll 99 for off spec. 30 seconds.")
    local s = wow.messages("S")[1]
    eq(s[3], "18000")
    eq(s[4], "council")
    eq(s[6], "Kadmai Moonwhisper")
    eq(s[7], "Seren Vale,Doran Pike,Kadmai Moonwhisper")
    eq(s[8], SASH)
    eq(ns.CouncilSession().phase, "bids")
    eq(ns.CurrentRoll(), nil, "no roll")
    wow.wait(20)
    eq(lastSaid(), "10 seconds left to bid on " .. SASH .. ".")
end)

test("bids from the pop-up and from rolls; a pass takes a bid back; a clear vote wins it", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms", "BIS", "first upgrade in weeks", "4.5", "16818")
    bid("Vespera Ashward", "ms", "Sidegrade", "", "1.0")
    wow.roll("Odo Fenwick", 70)          -- no addon: rolls main spec
    wow.roll("Bran Holloway", 40, 99)    -- off spec
    bid("Doran Pike", "ms")
    bid("Doran Pike", "pass")            -- changed his mind
    local s = ns.CouncilSession()
    eq(s.bids["ilsa marrow"].note, "first upgrade in weeks")
    eq(s.bids["ilsa marrow"].gain, 4.5)
    eq(s.bids["ilsa marrow"].gear[1], 16818)
    eq(s.bids["odo fenwick"].resp, "ms")
    eq(s.bids["odo fenwick"].roll, 70)
    eq(s.bids["odo fenwick"].trial, true)
    eq(s.bids["bran holloway"].resp, "os")
    eq(s.bids["doran pike"], nil)
    wow.wait(30)
    eq(lastSaid(), "Bids closed for " .. SASH .. ": 3 main spec. The council has 5 minutes.")
    eq(s.phase, "vote")
    bid("Seren Vale", "ms") -- too late
    eq(s.bids["seren vale"], nil)
    vote("Seren Vale", "ilsa marrow")
    vote("Doran Pike", "ilsa marrow")
    eq(s.phase, "vote", "waiting for the loot master's vote")
    ns.Vote("vespera ashward")
    eq(lastSaid(), "Ilsa Marrow wins " .. SASH .. " (council: council vote, 2 of 3).")
    local e = ns.db.log[1]
    eq(e.how, "council")
    eq(e.who, "Ilsa Marrow")
    eq(e.class, "WARLOCK")
    eq(e.note, 'council vote, 2 of 3; bid: BIS "first upgrade in weeks"')
    eq(e.tags, "BIS")
    eq(e.nms, 3)
    eq(e.nos, 1)
    eq(s.phase, "done")
    eq(wow.messages("E")[1][3], "Ilsa Marrow")
end)

test("a council member who bid main spec sits out the vote on it", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms")
    bid("Seren Vale", "ms")
    wow.wait(30)
    local s = ns.CouncilSession()
    eq(ns.CanVote(s, "seren vale"), false)
    vote("Seren Vale", "seren vale")  -- ignored
    eq(s.votes["seren vale"], nil)
    vote("Doran Pike", "ilsa marrow")
    ns.Vote("ilsa marrow")
    eq(lastSaid(), "Ilsa Marrow wins " .. SASH .. " (council: council vote, 2 of 2).")
end)

test("a split vote goes to a roll-off between the tied; only their rolls count", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms")
    bid("Vespera Ashward", "ms")
    bid("Bran Holloway", "ms")
    wow.wait(30)
    vote("Seren Vale", "ilsa marrow")
    vote("Doran Pike", "vespera ashward")
    ns.Vote("bran holloway")
    assert(wow.said():find("The council is split on " .. SASH, 1, true), wow.said())
    eq(lastSaid(), "Roll-off for " .. SASH .. " between Bran Holloway, Ilsa Marrow, Vespera Ashward: /roll. 30 seconds.")
    wow.roll("Odo Fenwick", 100)      -- not in it
    wow.roll("Ilsa Marrow", 30)
    wow.roll("Vespera Ashward", 80, 99) -- an off-spec range still counts in a roll-off
    wow.roll("Bran Holloway", 55)
    wow.wait(30)
    eq(lastSaid(), "Vespera Ashward wins " .. SASH .. " (council: roll-off after a split vote, 80).")
    eq(ns.db.log[1].how, "council")
    eq(ns.CouncilSession().phase, "done")
end)

test("time up: the most votes wins; with no votes at all, every main-spec bid rolls off", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms")
    bid("Vespera Ashward", "ms")
    wow.wait(30)
    vote("Seren Vale", "vespera ashward")
    wow.wait(299)
    eq(ns.CouncilSession().phase, "vote")
    wow.wait(1)
    eq(lastSaid(), "Vespera Ashward wins " .. SASH .. " (council: council vote, 1 of 1).")

    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms")
    bid("Vespera Ashward", "ms")
    wow.wait(330)
    eq(lastSaid(), "Roll-off for " .. SASH .. " between Ilsa Marrow, Vespera Ashward: /roll. 30 seconds.")
end)

test("one main-spec bid gets it without a vote", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms", "BIS")
    bid("Bran Holloway", "os")
    wow.wait(30)
    eq(lastSaid(), "Ilsa Marrow wins " .. SASH .. " (council: the only main-spec bid).")
end)

test("only off-spec bids: they roll off, and it's logged as off spec", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Bran Holloway", "os")
    wow.roll("Odo Fenwick", 20, 99)
    wow.wait(30)
    assert(wow.said():find("No main-spec bids for " .. SASH .. "; off spec rolls.", 1, true))
    wow.roll("Bran Holloway", 10)
    wow.roll("Odo Fenwick", 90)
    wow.wait(30)
    eq(lastSaid(), "Odo Fenwick wins " .. SASH .. " (council: off-spec roll, 90).")
    eq(ns.db.log[1].how, "os")
end)

test("no bids: the loot master disenchants or banks it", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    wow.wait(30)
    eq(lastSaid(), "Nobody wants " .. SASH .. ": the loot master disenchants or banks it.")
    eq(ns.CouncilSession().phase, "done")
    eq(#ns.db.log, 0)
end)

test("/nlc award gives it to a candidate with a reason; /nlc stop and cancel", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    bid("Ilsa Marrow", "ms")
    bid("Vespera Ashward", "ms")
    wow.type("/nlc stop") -- closes bids early
    eq(ns.CouncilSession().phase, "vote")
    wow.type("/nlc award Vespera Ashward, Warlock priority; Ilsa won the last one")
    eq(lastSaid(), "Vespera Ashward wins " .. SASH .. " (council: Warlock priority; Ilsa won the last one).")
    wow.type("/nlc start " .. SASH)
    wow.type("/nlc cancel")
    eq(lastSaid(), "Council for " .. SASH .. " called off.")
end)

test("/nlc start <item> roll rolls a council item instead", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH .. " roll")
    eq(wow.sent[1][1], "Roll for " .. SASH .. ": /roll for main spec, /roll 99 for off spec. 30 seconds.")
    eq(ns.CouncilSession(), nil)
end)

test("no council set: the loot master decides alone, and is told so", function()
    local ns = start()
    wow.raid({ ILSA, VESPERA })
    wow.type("/nlc council " .. SASH)
    wow.type("/nlc start " .. SASH)
    assert(printed():find("No council set", 1, true))
    eq(ns.CouncilSession().council[1], "Kadmai Moonwhisper")
end)

test("a council member's addon follows the loot master's session and sends its vote", function()
    local ns = start()
    wow.raid({ SEREN, DORAN, ILSA, VESPERA })
    wow.message("Seren Vale", "RAID", "S", 301, 18000, "council", 30, "Seren Vale", "Seren Vale,Kadmai Moonwhisper", SASH)
    local s = ns.CouncilSession()
    eq(s.sid, 301)
    eq(s.mine, nil)
    eq(s.link, SASH)
    eq(s.phase, "bids")
    wow.message("Ilsa Marrow", "WHISPER", "B", 301, "ms", "BIS", "", "2.0", "")
    eq(s.bids["ilsa marrow"].resp, "ms")
    wow.message("Seren Vale", "WHISPER", "P", 301, "vote", 300)
    eq(s.phase, "vote")
    ns.Vote("ilsa marrow")
    local v = wow.messages("V")
    eq(#v, 1, "to Seren (the player is the other council member)")
    eq(v[1].target, "Seren Vale")
    eq(v[1][3], "ilsa marrow")
    eq(s.votes["kadmai moonwhisper"], "ilsa marrow")
    wow.message("Seren Vale", "RAID", "E", 301, "Ilsa Marrow")
    eq(s.phase, "done")
    eq(s.winner, "Ilsa Marrow")
end)

test("a raider who isn't on the council keeps no session", function()
    local ns = start()
    wow.raid({ SEREN, ILSA })
    wow.message("Seren Vale", "RAID", "S", 301, 18000, "council", 30, "Seren Vale", "Seren Vale", SASH)
    eq(ns.CouncilSession(), nil)
end)
