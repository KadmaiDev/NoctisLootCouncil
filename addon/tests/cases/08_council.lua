test("no roll can start while a council item is open: its rolls would be taken as bids", function()
    local ns = lootMaster()
    wow.type("/nlc start " .. SASH)
    wow.type("/nlc start " .. wow.link(16818, "Netherwind Belt", 4) .. " roll")
