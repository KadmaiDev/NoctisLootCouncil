-- Loot discovery: drops seen in raids go into the list, with their boss and a count.

local LUCIFRON, LUCIFRON_NPC = 663, 12118
local CHOKER = wow.link(17109, "Choker of Enlightenment", 4)
local BOOTS = wow.link(18870, "Felheart Gloves", 4)
local BLUE = wow.link(16802, "Blue Trash Ring", 3)
local GREEN = wow.link(16800, "Green Belt", 2)

test("a boss's corpse: its items are listed under the boss, and the corpse is learned", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.wait(20)
    local corpse = wow.npc(LUCIFRON_NPC)
    wow.open({ { CHOKER, 4, corpse }, { BOOTS, 4, corpse }, { GREEN, 2, corpse } })
    local item = ns.db.items[17109]
    eq(item.seen, 1)
    eq(item.from.e663, 1)
    eq(item.q, 4)
    eq(item.inst, 409)
    eq(ns.db.items[16800], nil, "below rare is not recorded")
    eq(ns.db.bossSources["n" .. LUCIFRON_NPC], LUCIFRON)
    eq(ns.db.encounters[LUCIFRON].name, "Lucifron")
    eq(ns.db.instances[409], "Molten Core")
    assert(printed():find("First time seen: " .. CHOKER .. " from Lucifron", 1, true), printed())
end)

test("opening the same window again, or LOOT_READY and LOOT_OPENED both, counts once and tells once", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    local corpse = wow.npc(LUCIFRON_NPC)
    wow.open({ { CHOKER, 4, corpse } })
    wow.close()
    wow.open({ { CHOKER, 4, corpse } })
    eq(ns.db.items[17109].seen, 1)
    local _, told = printed():gsub("First time seen", "")
    eq(told, 1)
end)

test("two copies in the window are two drops; chat lines for them add nothing", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    local corpse = wow.npc(LUCIFRON_NPC)
    wow.open({ { CHOKER, 4, corpse }, { CHOKER, 4, corpse } })
    wow.close()
    wow.receives("Tarnia Moonwhisper", CHOKER)
    wow.receives("Vespera Ashward", CHOKER)
    eq(ns.db.items[17109].seen, 2)
    eq(ns.db.items[17109].from.e663, 2)
end)

test("a later kill is recognised by the corpse alone, even opened long after", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    wow.close()
    wow.wait(7 * 24 * 3600)
    clearPrinted()
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } }) -- no ENCOUNTER_END seen this time
    eq(ns.db.items[17109].seen, 2)
    eq(ns.db.items[17109].from.e663, 2)
    assert(not printed():find("First time seen"), printed())
end)

test("the list carries over to the next session", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    local saved = NoctisLootCouncilDB
    ns = start(saved)
    eq(ns.db.items[17109].seen, 1)
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    eq(ns.db.items[17109].seen, 2)
end)

test("a known item's decision is shown when it drops", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    wow.type("/nlc council " .. CHOKER .. " Priest priority")
    wow.close()
    clearPrinted()
    wow.wait(3600)
    wow.kill(LUCIFRON, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    assert(printed():find(CHOKER .. ": council item · Priest priority", 1, true), printed())
end)

test("trash loot in a raid is listed without a boss", function()
    local ns = start()
    wow.open({ { BLUE, 3, wow.npc(11666) } })
    local item = ns.db.items[16802]
    eq(item.seen, 1)
    eq(item.from.n11666, 1)
    assert(printed():find("from trash", 1, true), printed())
end)

test("the first corpse after a kill is the boss's; trash opened later is not", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(LUCIFRON_NPC) } })
    wow.close()
    wow.open({ { BLUE, 3, wow.npc(11666) } })
    eq(ns.db.items[16802].from.n11666, 1)
    eq(ns.db.items[16802].from.e663, nil)
    eq(ns.db.bossSources.n11666, nil)
end)

test("a boss's chest is learned like a corpse", function()
    local ns = start()
    wow.kill(671, "Majordomo Executus")
    wow.open({ { CHOKER, 4, wow.object(179703) } })
    eq(ns.db.bossSources.o179703, 671)
    eq(ns.db.items[17109].from.e671, 1)
end)

test("only raids are recorded, unless dungeons are switched on", function()
    local ns = start()
    wow.instance = { "Ragefire Chasm", "party", 1, "Normal", 5, 0, false, 389 }
    wow.open({ { CHOKER, 4, wow.npc(11520) } })
    eq(ns.db.items[17109], nil)
    wow.instance = { "Elwynn Forest", "none", 0, "", 0, 0, false, 0 }
    wow.open({ { CHOKER, 4, wow.npc(100) } })
    eq(ns.db.items[17109], nil)
    wow.type("/nlc dungeons on")
    wow.instance = { "Ragefire Chasm", "party", 1, "Normal", 5, 0, false, 389 }
    wow.open({ { CHOKER, 4, wow.npc(11520) } })
    eq(ns.db.items[17109].seen, 1)
    eq(ns.db.instances[389], "Ragefire Chasm")
end)

test("chat: a receipt after a kill counts as the boss's when the item is new to the list", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.receives("Tarnia Moonwhisper", BOOTS)
    eq(ns.db.items[18870].seen, 1)
    eq(ns.db.items[18870].from.e663, 1)
end)

test("chat: an item known from elsewhere isn't credited to the recent boss", function()
    local ns = start()
    wow.open({ { BLUE, 3, wow.npc(11666) } })
    wow.close()
    wow.kill(LUCIFRON, "Lucifron")
    wow.receives("Tarnia Moonwhisper", BLUE)
    eq(ns.db.items[16802].seen, 1)
    eq(ns.db.items[16802].from.e663, nil)
end)

test("chat: roll and choice lines don't count, and nothing counts long after a kill", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.fire("CHAT_MSG_LOOT", LOOT_ROLL_NEED:format("Tarnia Moonwhisper", BOOTS))
    eq(ns.db.items[18870], nil)
    wow.wait(3600)
    wow.receives("Tarnia Moonwhisper", BOOTS)
    eq(ns.db.items[18870].seen, 0, "listed, but no kill to count it under")
    eq(ns.db.items[18870].from, nil)
end)

test("chat: the receipt pattern comes from the client's own text, including %1$s forms", function()
    local ns = start()
    local p = ns.ChatPattern("%1$s erhält Beute: %2$s.")
    assert(("Tarnia erhält Beute: " .. BOOTS .. "."):find(p), p)
    assert(not ("Tarnia würfelt: " .. BOOTS):find(p))
end)

test("group loot roll windows count, one per window", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.rolls[1] = { BOOTS, 4 }
    wow.rolls[2] = { BOOTS, 4 }
    wow.fire("START_LOOT_ROLL", 1, 60000)
    wow.fire("START_LOOT_ROLL", 2, 60000)
    wow.receives("Tarnia Moonwhisper", BOOTS)
    eq(ns.db.items[18870].seen, 2)
end)

test("ENCOUNTER_LOOT_RECEIVED names its boss directly", function()
    local ns = start()
    wow.fire("ENCOUNTER_LOOT_RECEIVED", 664, 18870, BOOTS, 1, "Magmadar", "HUNTER")
    eq(ns.db.items[18870].from.e664, 1)
end)

test("quality: the item cache first, then the link's colour, including the newer colour codes", function()
    local ns = start()
    wow.fire("CHAT_MSG_LOOT", LOOT_ITEM:format("Tarnia", "|cnIQ4:|Hitem:20001::::|h[New Epic]|h|r"))
    eq(ns.db.items[20001].q, 4)
    wow.qualities[20002] = 2
    wow.fire("CHAT_MSG_LOOT", LOOT_ITEM:format("Tarnia", wow.link(20002, "Looks Epic", 4)))
    eq(ns.db.items[20002], nil, "the cache says uncommon")
end)

test("secret values are skipped, never looked at", function()
    local ns = start()
    wow.kill(LUCIFRON, "Lucifron")
    wow.fire("CHAT_MSG_LOOT", wow.SECRET)
    wow.open({ { wow.SECRET, 4, wow.npc(LUCIFRON_NPC) }, { CHOKER, 4, wow.SECRET } })
    eq(ns.db.items[17109].seen, 1)
    wow.fire("ENCOUNTER_END", wow.SECRET, "x", 9, 40, 1)
    wow.instance = { wow.SECRET, wow.SECRET, 9, "", 40, 0, false, wow.SECRET }
    wow.open({ { BOOTS, 4, wow.npc(1) } })
    eq(ns.db.items[18870], nil)
end)

test("money in the window is ignored", function()
    local ns = start()
    wow.open({ { money = true }, { CHOKER, 4, wow.npc(5) } })
    eq(ns.db.items[17109].seen, 1)
end)
