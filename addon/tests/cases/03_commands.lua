-- /nlc: the list and deciding how items are handled.

local CHOKER = wow.link(17109, "Choker of Enlightenment", 4)
local HELM = wow.link(16866, "Helm of Might", 4)
local HELM2 = wow.link(16867, "Helm of Might Reborn", 4)

local function withItems()
    local ns = start()
    wow.kill(663, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(12118) }, { HELM, 4, wow.npc(12118) } })
    wow.close()
    wow.open({ { HELM2, 4, wow.npc(11666) } })
    wow.close()
    clearPrinted()
    return ns
end

test("/nlc alone lists the commands", function()
    start()
    wow.type("/nlc")
    assert(printed():find("/nlc loot", 1, true), printed())
    assert(printed():find("/nlc council", 1, true))
end)

test("council and roll by shift-clicked link, with a note", function()
    local ns = withItems()
    wow.type("/nlc council " .. CHOKER .. " Priest priority")
    eq(ns.db.items[17109].handling, "council")
    eq(ns.db.items[17109].note, "Priest priority")
    assert(printed():find(CHOKER .. " is a council item.", 1, true), printed())
    wow.type("/nlc roll " .. CHOKER)
    eq(ns.db.items[17109].handling, "roll")
    eq(ns.db.items[17109].note, "Priest priority", "no new note keeps the old one")
end)

test("by name: the longest listed name the text starts with, the rest is the note", function()
    local ns = withItems()
    wow.type("/nlc council helm of might reborn Warriors first")
    eq(ns.db.items[16867].handling, "council")
    eq(ns.db.items[16867].note, "Warriors first")
    eq(ns.db.items[16866].handling, nil)
    wow.type("/nlc roll Helm of Might")
    eq(ns.db.items[16866].handling, "roll")
end)

test("by item ID, and undecided", function()
    local ns = withItems()
    wow.type("/nlc council 17109")
    wow.type("/nlc undecided 17109")
    eq(ns.db.items[17109].handling, nil)
end)

test("an item not in the list is refused, saying so", function()
    local ns = withItems()
    wow.type("/nlc council Thunderfury")
    assert(printed():find("Not in the list: Thunderfury", 1, true), printed())
end)

test("notes, and forgetting an item", function()
    local ns = withItems()
    wow.type("/nlc note 17109 Holy priests")
    eq(ns.db.items[17109].note, "Holy priests")
    wow.type("/nlc note 17109")
    eq(ns.db.items[17109].note, nil)
    wow.type("/nlc forget " .. HELM)
    eq(ns.db.items[16866], nil)
end)

test("/nlc loot lists by boss, unknown sources last, with counts and decisions", function()
    local ns = withItems()
    wow.type("/nlc council " .. CHOKER .. " Priest priority")
    clearPrinted()
    wow.type("/nlc loot")
    local out = printed()
    local boss = out:find("Molten Core · Lucifron", 1, true)
    local none = out:find("No known boss", 1, true)
    assert(boss and none and boss < none, out)
    assert(out:find(CHOKER .. " · ×1 · council · Priest priority", 1, true), out)
    assert(out:find(HELM2 .. " · ×1", 1, true), out)
    clearPrinted()
    wow.type("/nlc loot reborn")
    assert(not printed():find("Choker", 1, true), printed())
    assert(printed():find("Reborn", 1, true))
    clearPrinted()
    wow.type("/nlc loot zzz")
    assert(printed():find('No listed item matches "zzz"', 1, true), printed())
end)

test("/nlc loot with nothing seen yet says so", function()
    start()
    wow.type("/nlc loot")
    assert(printed():find("No raid drops seen yet.", 1, true), printed())
end)

test("/nlc quality sets the lowest quality recorded", function()
    local ns = start()
    wow.type("/nlc quality 4")
    eq(ns.db.minQuality, 4)
    assert(printed():find("quality 4 (Epic)", 1, true), printed())
    wow.open({ { wow.link(1, "Blue", 3), 3, wow.npc(5) } })
    eq(ns.db.items[1], nil)
    wow.type("/nlc quality 3")
    eq(ns.db.minQuality, nil, "the default isn't stored")
    wow.type("/nlc quality 9")
    eq(ns.db.minQuality, nil)
end)

test("an item known from outside our raids can be decided before it drops: by link, or by ID once it loads", function()
    local ns = start()
    local SASH = wow.link(18000, "Sash of the Unseen", 4)
    wow.type("/nlc council " .. SASH .. " Warlock priority")
    local item = ns.db.items[18000]
    eq(item.handling, "council")
    eq(item.note, "Warlock priority")
    eq(item.seen, 0)
    eq(item.q, 4)
    assert(printed():find("Added " .. SASH .. " to the list (not seen in our raids yet).", 1, true), printed())
    wow.type("/nlc roll 18001")
    eq(ns.db.items[18001].link, "item:18001", "a placeholder until the game loads it")
    eq(wow.requested[1], 18001)
    wow.itemLoads(18001, "Band of the Unseen", 4)
    eq(ns.db.items[18001].link, wow.link(18001, "Band of the Unseen", 4))
    wow.cache[18002] = { "Cached Cloak", 3 }
    wow.type("/nlc note 18002 Tanks")
    eq(ns.db.items[18002].link, wow.link(18002, "Cached Cloak", 3), "already loaded: no wait")
    eq(ns.db.items[18002].q, 3)
    clearPrinted()
    wow.type("/nlc loot")
    local out = printed()
    assert(out:find("Not seen in our raids yet", 1, true), out)
    assert(out:find(SASH .. " · ×0 · council · Warlock priority", 1, true), out)
end)

test("an item decided before it drops: its first drop tells the decision, and it's counted under the boss", function()
    local ns = start()
    local SASH = wow.link(18000, "Sash of the Unseen", 4)
    wow.type("/nlc council " .. SASH .. " Warlock priority")
    clearPrinted()
    wow.kill(663, "Lucifron")
    wow.open({ { SASH, 4, wow.npc(12118) } })
    assert(printed():find(SASH .. ": council item · Warlock priority", 1, true), printed())
    assert(not printed():find("First time seen", 1, true), printed())
    eq(ns.db.items[18000].seen, 1)
    eq(ns.db.items[18000].from.e663, 1)
    clearPrinted()
    wow.type("/nlc loot")
    assert(not printed():find("Not seen in our raids yet", 1, true), printed())
end)

test("an undecided item added unseen still gets the first-time message when it first drops", function()
    local ns = start()
    local SASH = wow.link(18000, "Sash of the Unseen", 4)
    wow.type("/nlc note " .. SASH .. " ask Sethaan")
    clearPrinted()
    wow.kill(663, "Lucifron")
    wow.open({ { SASH, 4, wow.npc(12118) } })
    assert(printed():find("First time seen: " .. SASH .. " from Lucifron", 1, true), printed())
end)
