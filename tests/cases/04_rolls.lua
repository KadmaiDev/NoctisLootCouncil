-- Rolls: tiers, members before trials, ties, and announcing it all in raid chat.

local CHOKER = wow.link(17109, "Choker of Enlightenment", 4)
local HELM = wow.link(16866, "Helm of Might", 4)

local VESPERA = { "Vespera", "Ashward", rank = "Raider" }
local TARNIA = { "Tarnia", "Moonwhisper", rank = "Core" }
local BRAN = { "Bran", "Holloway", rank = "Social" }
local ODO = { "Odo", "Fenwick", rank = "Trial" }

local function raid(...)
    local ns = start()
    wow.raid({ ... })
    clearPrinted()
    return ns
end

local function lastSaid() return wow.sent[#wow.sent] and wow.sent[#wow.sent][1] end

test("a roll: announced in raid chat, the highest main-spec roll wins after 30 seconds, and it's logged", function()
    local ns = raid(VESPERA, TARNIA)
    wow.type("/nlc start " .. CHOKER)
    eq(wow.sent[1][1], "Roll for " .. CHOKER .. ": /roll for main spec, /roll 99 for off spec. 30 seconds.")
    eq(wow.sent[1][2], "RAID")
    wow.roll("Vespera Ashward", 42)
    wow.roll("Tarnia Moonwhisper", 87)
    wow.wait(29)
    eq(#wow.sent, 1, "nothing before the time is up")
    wow.wait(1)
    eq(lastSaid(), "Tarnia Moonwhisper wins " .. CHOKER .. " (main spec, 87).")
    local e = ns.db.log[1]
    eq(e.who, "Tarnia Moonwhisper")
    eq(e.id, 17109)
    eq(e.how, "ms")
    eq(e.roll, 87)
    eq(ns.CurrentRoll(), nil)
    assert(printed():find("1. Tarnia Moonwhisper 87 · main spec", 1, true), printed())
end)

test("tiers: main spec beats a second main spec, which beats off spec, whatever the rolls", function()
    local ns = raid(VESPERA, TARNIA, BRAN)
    wow.type("/nlc start " .. HELM)
    wow.roll("Tarnia Moonwhisper", 90)
    wow.wait(30) -- Tarnia has a main-spec win tonight now
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Bran Holloway", 99, 99) -- off spec
    wow.roll("Tarnia Moonwhisper", 95) -- second main spec
    wow.roll("Vespera Ashward", 3) -- main spec
    wow.wait(30)
    eq(lastSaid(), "Vespera Ashward wins " .. CHOKER .. " (main spec, 3).")
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Bran Holloway", 99, 99)
    wow.roll("Tarnia Moonwhisper", 2)
    wow.wait(30)
    eq(lastSaid(), "Tarnia Moonwhisper wins " .. CHOKER .. " (second main spec, 2).")
    eq(ns.db.log[3].how, "ms2")
end)

test("an off-spec win doesn't count as a win tonight; a new night or 12 hours clears wins", function()
    local ns = raid(VESPERA)
    wow.type("/nlc start " .. HELM)
    wow.roll("Vespera Ashward", 50, 99)
    wow.wait(30)
    eq(ns.db.log[1].how, "os")
    eq(ns.WonTonight("vespera ashward"), false)
    wow.type("/nlc start " .. HELM)
    wow.roll("Vespera Ashward", 50)
    wow.wait(30)
    eq(ns.WonTonight("vespera ashward"), true)
    wow.wait(60)
    wow.type("/nlc newnight")
    eq(ns.WonTonight("vespera ashward"), false)
    ns.db.night = nil
    eq(ns.WonTonight("vespera ashward"), true)
    wow.wait(12 * 3600)
    eq(ns.WonTonight("vespera ashward"), false)
end)

test("a trial wins only if no member rolled in that tier", function()
    local ns = raid(VESPERA, ODO, BRAN)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Odo Fenwick", 100)
    wow.roll("Bran Holloway", 1) -- socials are members for rolls
    wow.wait(30)
    eq(lastSaid(), "Bran Holloway wins " .. CHOKER .. " (main spec, 1).")
    wow.type("/nlc newnight")
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Odo Fenwick", 4)
    wow.roll("Vespera Ashward", 99, 99)
    wow.wait(30)
    eq(lastSaid(), "Odo Fenwick wins " .. CHOKER .. " (main spec, trial, 4).", "a trial's main spec beats a member's off spec")
end)

test("trial ranks: by default any rank with \"trial\" in it, or the ranks set; only our guild's", function()
    local ns = raid({ "Odo", "Fenwick", rank = "Trial Raider" }, { "Ula", "Brandt", rank = "Recruit" },
        { "Pell", "Varga", rank = "Trial", guild = "Other Guild" })
    local function trial(name) return ns.IsTrial(ns.GroupMember(name).unit) end
    eq(trial("Odo Fenwick"), true)
    eq(trial("Ula Brandt"), false)
    eq(trial("Pell Varga"), false, "another guild's trial rank doesn't count")
    wow.type("/nlc trials Recruit, Initiate")
    eq(trial("Ula Brandt"), true)
    eq(trial("Odo Fenwick"), false)
    assert(printed():find("Trial ranks: Recruit, Initiate.", 1, true), printed())
    wow.type("/nlc trials default")
    eq(ns.db.trialRanks, nil)
end)

test("a tie is re-rolled by those tied, and ends as soon as they all have", function()
    local ns = raid(VESPERA, TARNIA, BRAN)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera Ashward", 80)
    wow.roll("Tarnia Moonwhisper", 80)
    wow.roll("Bran Holloway", 79)
    wow.wait(30)
    eq(lastSaid(), "Tie for " .. CHOKER .. ": Tarnia Moonwhisper, Vespera Ashward. Roll again, 30 seconds.")
    wow.roll("Bran Holloway", 100) -- not in the tie
    wow.roll("Vespera Ashward", 12)
    wow.roll("Vespera Ashward", 99) -- the first re-roll counts
    eq(ns.CurrentRoll() ~= nil, true)
    wow.roll("Tarnia Moonwhisper", 30)
    eq(lastSaid(), "Tarnia Moonwhisper wins " .. CHOKER .. " (main spec, 30).")
    eq(ns.db.log[1].roll, 30)
end)

test("a tie nobody re-rolls goes to the loot master; one who does re-roll wins", function()
    local ns = raid(VESPERA, TARNIA)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera Ashward", 80)
    wow.roll("Tarnia Moonwhisper", 80)
    wow.wait(60)
    eq(lastSaid(), "Nobody re-rolled for " .. CHOKER .. "; the loot master decides.")
    eq(#ns.db.log, 0)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera Ashward", 80)
    wow.roll("Tarnia Moonwhisper", 80)
    wow.wait(30)
    wow.roll("Vespera Ashward", 5)
    wow.wait(30)
    eq(lastSaid(), "Vespera Ashward wins " .. CHOKER .. " (main spec, 5).")
end)

test("only the first roll counts; other ranges, strangers and rolls with nothing running don't", function()
    local ns = raid(VESPERA, TARNIA)
    wow.roll("Vespera Ashward", 100)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera Ashward", 10)
    wow.roll("Vespera Ashward", 90)
    wow.roll("Tarnia Moonwhisper", 100, 50)
    assert(printed():find("Ignored Tarnia Moonwhisper's roll of 100 (1-50)", 1, true), printed())
    wow.roll("Tarnia Moonwhisper", 100, 100, 2)
    wow.roll("Somebody Else", 100)
    wow.roll("Tarnia Moonwhisper", 9)
    wow.wait(30)
    eq(lastSaid(), "Vespera Ashward wins " .. CHOKER .. " (main spec, 10).")
end)

test("a roll line with a first name only counts when one raider has that first name", function()
    local ns = raid(VESPERA, TARNIA, { "Tarnia", "Brook", rank = "Raider" })
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera", 20)
    wow.roll("Tarnia", 90) -- two Tarnias: can't tell which
    wow.wait(30)
    eq(lastSaid(), "Vespera Ashward wins " .. CHOKER .. " (main spec, 20).")
end)

test("nobody rolls: said so, nothing logged", function()
    local ns = raid(VESPERA)
    wow.type("/nlc start " .. CHOKER)
    wow.wait(30)
    eq(lastSaid(), "Nobody rolled for " .. CHOKER .. ".")
    eq(#ns.db.log, 0)
end)

test("stop ends it early, cancel calls it off, and one roll at a time", function()
    local ns = raid(VESPERA)
    wow.type("/nlc stop")
    assert(printed():find("No roll running.", 1, true), printed())
    wow.type("/nlc start " .. CHOKER)
    wow.type("/nlc start " .. HELM)
    assert(printed():find("Already rolling for " .. CHOKER, 1, true), printed())
    wow.roll("Vespera Ashward", 7)
    wow.type("/nlc stop")
    eq(lastSaid(), "Vespera Ashward wins " .. CHOKER .. " (main spec, 7).")
    local n = #wow.sent
    wow.wait(30)
    eq(#wow.sent, n, "the old round's timer does nothing")
    wow.type("/nlc start " .. HELM)
    wow.type("/nlc cancel")
    eq(lastSaid(), "Roll for " .. HELM .. " called off.")
    wow.roll("Vespera Ashward", 7)
    wow.wait(30)
    eq(#ns.db.log, 1)
end)

test("start by a listed item's name; a missing item is refused", function()
    local ns = raid(VESPERA)
    wow.kill(663, "Lucifron")
    wow.open({ { CHOKER, 4, wow.npc(12118) } })
    wow.close()
    wow.type("/nlc start choker of enlightenment")
    eq(lastSaid(), "Roll for " .. CHOKER .. ": /roll for main spec, /roll 99 for off spec. 30 seconds.")
    wow.type("/nlc cancel")
    wow.type("/nlc start Thunderfury")
    assert(printed():find("Roll for what?", 1, true), printed())
end)

test("when the game blocks chat, or solo, the announcements are shown to the loot master", function()
    local ns = raid(VESPERA)
    wow.lockdown = true
    wow.type("/nlc start " .. CHOKER)
    eq(#wow.sent, 0)
    assert(printed():find("please pass it on: Roll for " .. CHOKER, 1, true), printed())
    wow.type("/nlc cancel")
    ns = start()
    clearPrinted()
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Kadmai Moonwhisper", 61)
    wow.wait(30)
    eq(#wow.sent, 0)
    assert(printed():find("Kadmai Moonwhisper wins " .. CHOKER .. " (main spec, 61).", 1, true), printed())
end)

test("a secret chat line is ignored", function()
    local ns = raid(VESPERA)
    wow.type("/nlc start " .. CHOKER)
    wow.fire("CHAT_MSG_SYSTEM", wow.SECRET)
    wow.roll("Vespera Ashward", 5)
    wow.wait(30)
    eq(#ns.db.log, 1)
end)

test("undo removes the last award, and with it the win", function()
    local ns = raid(VESPERA)
    wow.type("/nlc start " .. CHOKER)
    wow.roll("Vespera Ashward", 5)
    wow.wait(30)
    wow.type("/nlc wins")
    assert(printed():find("Vespera Ashward · " .. CHOKER, 1, true), printed())
    wow.type("/nlc undo")
    eq(#ns.db.log, 0)
    eq(ns.WonTonight("vespera ashward"), false)
    clearPrinted()
    wow.type("/nlc wins")
    assert(printed():find("No main-spec wins tonight.", 1, true), printed())
end)

test("a damaged log and trial list are repaired at load", function()
    local ns = start({
        log = { { who = "A B", at = 5, how = "ms", roll = "x" }, "junk", { who = "C D" }, [5] = { who = "E F", at = 6, how = "os" } },
        trialRanks = { "Trial", 4, "Recruit" },
        night = "late",
    })
    eq(#ns.db.log, 2)
    eq(ns.db.log[1].who, "A B")
    eq(ns.db.log[1].roll, nil)
    eq(ns.db.log[2].who, "E F")
    eq(#ns.db.trialRanks, 2)
    eq(ns.db.trialRanks[2], "Recruit")
    eq(ns.db.night, nil)
end)
